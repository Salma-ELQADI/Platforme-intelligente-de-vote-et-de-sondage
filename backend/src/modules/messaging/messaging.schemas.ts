import { z } from 'zod';

export const MESSAGE_MAX_LENGTH = 2000;
export const GROUP_MAX_MEMBERS = 50;

/**
 * Message text: line endings normalised, invisible control characters
 * removed (tabs and new lines are kept), outer whitespace trimmed.
 * The text is stored as typed and always rendered as text by the client
 * (never as HTML), so no HTML escaping happens here.
 */
export const messageBodySchema = z
  .string({ error: 'Le message est obligatoire' })
  .transform((s) => s.replace(/\r\n?/g, '\n').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '').trim())
  .pipe(
    z
      .string()
      .min(1, 'Le message est vide')
      .max(MESSAGE_MAX_LENGTH, `Le message ne peut pas dépasser ${MESSAGE_MAX_LENGTH} caractères`),
  );

export const groupNameSchema = z
  .string({ error: 'Le nom du groupe est obligatoire' })
  .trim()
  .min(1, 'Le nom du groupe est obligatoire')
  .max(80, 'Le nom du groupe ne peut pas dépasser 80 caractères');

const userIds = z.array(z.uuid({ message: 'Identifiant invalide' })).max(GROUP_MAX_MEMBERS - 1, 'Trop de membres');

export const createDirectSchema = z.object({ userId: z.uuid({ message: 'Identifiant invalide' }) });

export const createGroupSchema = z.object({
  name: groupNameSchema,
  memberIds: userIds.min(1, 'Ajoutez au moins un membre'),
});

export const updateGroupSchema = z.object({ name: groupNameSchema });

export const addMembersSchema = z.object({ userIds: userIds.min(1, 'Ajoutez au moins un membre') });

export const updateMemberSchema = z.object({ role: z.enum(['ADMIN', 'MEMBER']) });

export const sendMessageSchema = z.object({
  body: messageBodySchema,
  // Generated by the client (crypto.randomUUID) to make retries idempotent.
  clientId: z.uuid({ message: 'clientId invalide' }),
});

export const listConversationsQuerySchema = z.object({
  search: z.string().trim().max(80).optional(),
});

export const listMessagesQuerySchema = z
  .object({
    before: z.coerce.number().int().positive().optional(),
    after: z.coerce.number().int().min(0).optional(),
    limit: z.coerce.number().int().min(1).max(100).default(30),
  })
  .refine((q) => q.before === undefined || q.after === undefined, { message: 'before et after sont exclusifs' });

export const markReadSchema = z.object({ seq: z.number().int().min(0).optional() }).default({});

export const memberParams = z.object({
  id: z.uuid({ message: 'Identifiant invalide' }),
  userId: z.uuid({ message: 'Identifiant invalide' }),
});

// ---- Socket.IO payloads ----
export const socketSendSchema = sendMessageSchema.extend({ conversationId: z.uuid() });
export const socketConversationSchema = z.object({ conversationId: z.uuid() });
export const socketReadSchema = z.object({ conversationId: z.uuid(), seq: z.number().int().min(0).optional() });
export const socketTypingSchema = z.object({ conversationId: z.uuid(), isTyping: z.boolean() });

export type ListMessagesQuery = z.infer<typeof listMessagesQuerySchema>;
