-- =====================================================================
-- 003 - Private and group messaging, user preferences
--
-- conversations         one row per DIRECT (2 people) or GROUP conversation
-- conversation_members  who may read/write a conversation, their role and
--                       how far they have read
-- messages              persisted messages (Socket.IO only delivers them)
-- users.preferred_*     interface language and theme, loaded after login
-- =====================================================================

-- ---------------------------------------------------------------------
-- User preferences (1:1 with users, so plain columns rather than a table)
-- NULL locale / 'system' theme = "follow the browser".
-- ---------------------------------------------------------------------
ALTER TABLE users
  ADD COLUMN preferred_locale       VARCHAR(2),
  ADD COLUMN preferred_theme        VARCHAR(6) NOT NULL DEFAULT 'system',
  ADD COLUMN message_notifications  BOOLEAN    NOT NULL DEFAULT TRUE,
  ADD CONSTRAINT users_locale_check CHECK (preferred_locale IN ('fr', 'en', 'ar')),
  ADD CONSTRAINT users_theme_check  CHECK (preferred_theme IN ('system', 'light', 'dark'));

-- ---------------------------------------------------------------------
-- conversations
-- ---------------------------------------------------------------------
CREATE TABLE conversations (
  id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  type            VARCHAR(6)  NOT NULL,
  -- Groups only. A direct conversation is named after the other participant.
  name            VARCHAR(80),
  -- Kept as an audit field; the group keeps living if its creator deletes their account.
  created_by      UUID        REFERENCES users(id) ON DELETE SET NULL,
  -- DIRECT only: "<smallest user id>:<largest user id>". The UNIQUE constraint
  -- makes a second private conversation between the same two people impossible,
  -- even when both click "write" at the same moment.
  direct_key      TEXT,
  -- Denormalised for the conversation list ordering (updated on every message).
  last_message_at TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT conversations_type_check   CHECK (type IN ('DIRECT', 'GROUP')),
  CONSTRAINT conversations_direct_key   CHECK ((type = 'DIRECT') = (direct_key IS NOT NULL)),
  CONSTRAINT conversations_group_name   CHECK (
    (type = 'GROUP' AND name IS NOT NULL AND char_length(btrim(name)) >= 1) OR (type = 'DIRECT' AND name IS NULL)
  ),
  CONSTRAINT conversations_direct_key_unique UNIQUE (direct_key)
);

CREATE TRIGGER conversations_set_updated_at
  BEFORE UPDATE ON conversations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- conversation_members
-- A removed member's row is deleted: they lose access to the conversation
-- (history included) at once, which is the strictest reading of the rule.
-- ---------------------------------------------------------------------
CREATE TABLE conversation_members (
  conversation_id UUID        NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id         UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role            VARCHAR(6)  NOT NULL DEFAULT 'MEMBER',
  -- Sequence number (messages.seq) of the last message this member has read.
  -- Unread count = messages of others with a greater seq.
  last_read_seq   BIGINT      NOT NULL DEFAULT 0,
  joined_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT conversation_members_pkey PRIMARY KEY (conversation_id, user_id),
  CONSTRAINT conversation_members_role_check CHECK (role IN ('ADMIN', 'MEMBER'))
);

-- "My conversations" lookups.
CREATE INDEX conversation_members_user_idx ON conversation_members (user_id);

-- ---------------------------------------------------------------------
-- messages
-- ---------------------------------------------------------------------
CREATE TABLE messages (
  id              UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Strictly increasing, gap-tolerant ordering key. Used for display order,
  -- cursor pagination (?before=<seq>), catch-up after a reconnection
  -- (?after=<seq>) and read positions. Timestamps can tie; seq cannot.
  seq             BIGINT        GENERATED ALWAYS AS IDENTITY,
  conversation_id UUID          NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  -- SET NULL keeps the conversation readable if the author deletes their account.
  sender_id       UUID          REFERENCES users(id) ON DELETE SET NULL,
  body            VARCHAR(2000) NOT NULL,
  -- Id generated by the sending client. Retrying a send (lost ack, reconnection,
  -- double click) returns the original message instead of creating a duplicate.
  client_id       UUID          NOT NULL,
  created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

  CONSTRAINT messages_seq_unique       UNIQUE (seq),
  CONSTRAINT messages_body_not_blank   CHECK (char_length(btrim(body)) >= 1),
  CONSTRAINT messages_client_id_unique UNIQUE (sender_id, client_id)
);

-- History pages and unread counts: always "messages of conversation X ordered by seq".
CREATE INDEX messages_conversation_seq_idx ON messages (conversation_id, seq DESC);
